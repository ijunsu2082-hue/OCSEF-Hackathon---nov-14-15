/**
 * Predicate registry.
 *
 * A bundle cannot invent a field. Every claim predicate must appear here with a
 * unit, a value type and a closed domain. This is what makes "the number in the
 * UI" auditable: `facility.utilization_pct` is always a percentage in 0–105, and
 * a 0.75 ratio stored under it is a verification error, not a styling bug.
 *
 * `allow_inferred` is deliberately false for every physical measurement. An LLM
 * may propose a citation, but it may not author a nameplate, a coordinate or an
 * emission factor. Those require an observed source or an explicit model.
 */

import type { ClaimMethod } from "./schema";

export interface PredicateDefinition {
  id: string;
  label: string;
  unit: string | null;
  value_type: "number" | "string" | "boolean";
  min?: number;
  max?: number;
  integer?: boolean;
  enum_values?: string[];
  /** Only a registered formula may return null (e.g. payback when savings = 0). */
  nullable?: boolean;
  allowed_methods: ClaimMethod[];
  /** If true, an `inferred` claim is permitted. Defaults to false. */
  allow_inferred?: boolean;
  subject_prefix?: "facility" | "region";
  description: string;
}

const ALL: ClaimMethod[] = ["observed", "derived", "modeled", "inferred"];
const MEASURED: ClaimMethod[] = ["observed", "derived", "modeled"];

function def(definition: PredicateDefinition): PredicateDefinition {
  return { ...definition, allow_inferred: definition.allow_inferred ?? false };
}

